import math

import torch

from biotwin.data.dataset import H, LH
from biotwin.evaluate import interval_metrics_gaussian
from biotwin.models.mechanistic import PARAM_NAMES, MinimalModel
from biotwin.uncertainty import ADAPT_IDX, conformal_halfwidth, laplace_personalise


def test_conformal_covers_at_least_nominal():
    torch.manual_seed(0)
    r_cal, r_test = torch.randn(500, H), torch.randn(5000, H)
    hw = conformal_halfwidth(torch.zeros(500, H), r_cal, 0.8)
    cov = (r_test.abs() <= hw).float().mean()
    assert 0.77 < cov < 0.85


def test_gaussian_coverage_is_correct_for_correct_sigma():
    torch.manual_seed(0)
    y = torch.randn(20000, H) * 3
    m = interval_metrics_gaussian(torch.zeros_like(y), torch.full_like(y, 3.0), y)
    assert abs(m["cov80_all"] - 0.8) < 0.02 and abs(m["cov95_all"] - 0.95) < 0.01


def test_laplace_recovers_insulin_sensitivity():
    """Data generated by the model with SI x2: the MAP should move SI up and the posterior should cover it."""
    torch.manual_seed(0)
    model = MinimalModel()
    B = 64
    ins = torch.full((B, LH + H), 0.5)
    ins[torch.arange(B), torch.randint(LH - 24, LH + 2, (B,))] += 4.0
    carbs = torch.zeros(B, LH + H)
    carbs[torch.arange(B), torch.randint(LH - 30, LH, (B,))] += 50.0
    w = {"cgm_hist": torch.full((B, LH), 160.0), "ins": ins, "carbs": carbs, "basal": torch.full((B,), 0.5),
         "y": torch.zeros(B, H)}
    true_lt = model.log_theta.detach().clone()
    i_si = PARAM_NAMES.index("SI")
    true_lt[i_si] += math.log(2.0)
    with torch.no_grad():
        w["y"] = model(w, log_theta=true_lt) + torch.randn(B, H)
    phi, cov = laplace_personalise(model, w, torch.ones(H))
    j = ADAPT_IDX.index(i_si)
    err = (phi[j] - true_lt[i_si]).abs()
    assert err < 3 * cov[j, j].sqrt() + 0.05
